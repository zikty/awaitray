#!/usr/bin/env python3
"""The module graph of awaitray, read from its imports (stdlib only).

    python3 scripts/arch_graph.py          # rewrite the graph in docs/architecture.md
    python3 scripts/arch_graph.py --check  # fail if it's out of date (CI)

`scan()` is also what tests/test_architecture.py checks the layer rules
against, so the picture and the rules can't disagree.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "awaitray"
DOC = ROOT / "docs" / "architecture.md"
BEGIN = "<!-- arch-graph:begin (generated by scripts/arch_graph.py; don't edit) -->"
END = "<!-- arch-graph:end -->"


def modules(package: Path = PACKAGE) -> dict[str, Path]:
    """Dotted names inside the package ("controller", "features.links",
    "backends" for backends/__init__.py) → their files."""
    out = {}
    for path in sorted(package.rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        parts = list(path.relative_to(package).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()
        out[".".join(parts) or "__init__"] = path
    return out


def _resolve(name: str, known: dict[str, Path]) -> str | None:
    """The longest known module that `name` is or lives in."""
    parts = name.split(".")
    while parts:
        candidate = ".".join(parts)
        if candidate in known:
            return candidate
        parts.pop()
    return None


def scan(package: Path = PACKAGE) -> dict[str, tuple[set[str], set[str]]]:
    """Each module → (awaitray modules it imports, other top-level modules
    it imports). Every import counts: lazy ones and TYPE_CHECKING ones too."""
    known = modules(package)
    out: dict[str, tuple[set[str], set[str]]] = {}
    for name, path in known.items():
        internal: set[str] = set()
        external: set[str] = set()
        is_pkg = path.name == "__init__.py"
        here = name.split(".") if name != "__init__" else []
        pkg = here if is_pkg else here[:-1]
        for node in ast.walk(ast.parse(path.read_text(), str(path))):
            targets: list[str] = []
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name == "awaitray" or alias.name.startswith("awaitray."):
                        targets.append(alias.name.removeprefix("awaitray").lstrip("."))
                    else:
                        external.add(alias.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom):
                if node.level == 0:
                    mod = node.module or ""
                    if mod != "awaitray" and not mod.startswith("awaitray."):
                        external.add(mod.split(".")[0])
                        continue
                    base = mod.removeprefix("awaitray").lstrip(".").split(".")
                    base = [p for p in base if p]
                else:
                    base = pkg[: len(pkg) - (node.level - 1)] if node.level > 1 else list(pkg)
                    base += node.module.split(".") if node.module else []
                for alias in node.names:  # `from . import x` may name a module
                    targets.append(".".join([*base, alias.name]))
            for target in targets:
                found = _resolve(target, known) if target else None
                if found and found != name:
                    internal.add(found)
        out[name] = (internal, external)
    return out


def layer(name: str) -> str:
    if name == "backends" or name.startswith("backends."):
        return "backends"
    if name.startswith("features"):
        return "features"
    return "core"


def _node(name: str) -> str:
    """Backends collapse to one node per platform: their inner modules are
    one toolkit's business."""
    parts = name.split(".")
    return ".".join(parts[:2]) if parts[0] == "backends" else name


def mermaid(graph: dict[str, tuple[set[str], set[str]]]) -> str:
    nodes = sorted({_node(n) for n in graph} - {"__init__", "__main__"})
    edges = sorted(
        {
            (_node(src), _node(dst))
            for src, (deps, _ext) in graph.items()
            for dst in deps
            if _node(src) != _node(dst) and "__init__" not in (src, dst) and src != "__main__"
        }
    )
    ident = {n: n.replace(".", "_") for n in nodes}
    lines = ["```mermaid", "flowchart LR"]
    for group in ("core", "features", "backends"):
        members = [n for n in nodes if layer(n) == group]
        lines.append(f"  subgraph {group}")
        lines += [f'    {ident[n]}["{n}"]' for n in members]
        lines.append("  end")
    lines += [f"  {ident[a]} --> {ident[b]}" for a, b in edges if a in ident and b in ident]
    lines.append("```")
    return "\n".join(lines)


def render(doc: str, graph_text: str) -> str:
    start, end = doc.index(BEGIN), doc.index(END)
    return doc[: start + len(BEGIN)] + "\n" + graph_text + "\n" + doc[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the doc is out of date")
    args = parser.parse_args(argv)
    current = DOC.read_text()
    updated = render(current, mermaid(scan()))
    if args.check:
        if updated != current:
            print("graph out of date: run python3 scripts/arch_graph.py", file=sys.stderr)
            return 1
        return 0
    if updated != current:
        DOC.write_text(updated)
        print(f"updated {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
